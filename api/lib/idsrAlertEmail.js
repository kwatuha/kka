/**
 * Optional email queue log when IDSR alerts fire (DHA 10.2 partial).
 * Set IDSR_ALERT_EMAIL=comma-separated addresses and SMTP_HOST when mail is wired.
 */
function parseAlertEmails() {
  const raw = String(process.env.IDSR_ALERT_EMAIL || '').trim();
  if (!raw) return [];
  return raw
    .split(/[,;\s]+/)
    .map((e) => e.trim().toLowerCase())
    .filter((e) => e.includes('@'));
}

function isIdsrEmailEnabled() {
  const flag = String(process.env.IDSR_ALERT_EMAIL_ENABLED || 'true').toLowerCase();
  if (flag === 'false' || flag === '0' || flag === 'no') return false;
  return parseAlertEmails().length > 0;
}

async function notifyIdsrAlertEmail(alert) {
  if (!isIdsrEmailEnabled()) return { sent: 0, skipped: 'disabled_or_unconfigured' };
  const immediateOnly = String(process.env.IDSR_ALERT_EMAIL_IMMEDIATE_ONLY || 'true').toLowerCase() !== 'false';
  if (immediateOnly && alert.urgency !== 'immediate') {
    return { sent: 0, skipped: 'non_immediate' };
  }
  const recipients = parseAlertEmails();
  const subject = `[IDSR] ${alert.diseaseName || alert.diseaseCode}`;
  const body = [
    alert.summary || 'Notifiable condition detected',
    '',
    `Alert ID: ${alert.alertId}`,
    `Disease code: ${alert.diseaseCode || '—'}`,
    `Urgency: ${alert.urgency || '—'}`,
    '',
    'Generated by AZ CarePlus HMIS IDSR evaluate workflow.',
  ].join('\n');
  if (!process.env.SMTP_HOST) {
    console.info('[idsrAlertEmail] SMTP not configured — would send:', { to: recipients, subject, body });
    return { sent: 0, skipped: 'smtp_not_configured', recipients: recipients.length };
  }
  const { sendMail } = require('./smtpMailer');
  const result = await sendMail({
    to: recipients,
    subject,
    text: body,
  });
  if (result.ok) {
    console.info('[idsrAlertEmail] sent:', { to: recipients.join(','), messageId: result.messageId });
    return { sent: recipients.length, delivered: true, messageId: result.messageId };
  }
  console.warn('[idsrAlertEmail] send failed:', result.error);
  return { sent: 0, skipped: 'smtp_send_failed', error: result.error, recipients: recipients.length };
}

module.exports = { notifyIdsrAlertEmail, isIdsrEmailEnabled, parseAlertEmails };
