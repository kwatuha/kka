/**
 * Single-employee payslip PDF (client download / optional upload for email).
 */

import { branding } from "@/lib/branding"
import { drawFinanceLetterhead, kes, loadFinancePdf, parseAmount } from "@/lib/finance-pdf-utils"
import { sanitizePrintText } from "@/lib/sanitize-print-text"

export type PayslipRow = Record<string, unknown>

function fmtDate(d: unknown): string {
  if (!d) return "—"
  return String(d).slice(0, 10)
}

function line(
  pdf: import("@/lib/finance-pdf-utils").JsPdfDoc,
  label: string,
  value: string,
  y: number,
  bold = false
): number {
  pdf.setFont("helvetica", bold ? "bold" : "normal")
  pdf.setFontSize(10)
  pdf.text(sanitizePrintText(label), 14, y)
  pdf.text(sanitizePrintText(value), 196, y, { align: "right" })
  return y + 6
}

export async function buildPayslipPdf(payroll: PayslipRow): Promise<InstanceType<Awaited<ReturnType<typeof loadFinancePdf>>["jsPDF"]>> {
  const { jsPDF } = await loadFinancePdf()
  const pdf = new jsPDF({ orientation: "portrait", unit: "mm", format: "a4" })

  const period = `${fmtDate(payroll.payPeriodStart)} – ${fmtDate(payroll.payPeriodEnd)}`
  const subtitle = sanitizePrintText(
    `${payroll.payrollNumber || ""} · ${period} · Pay date ${fmtDate(payroll.paymentDate)}`
  )
  let y = await drawFinanceLetterhead(pdf, "Payslip", subtitle)

  pdf.setFontSize(11)
  pdf.setFont("helvetica", "bold")
  pdf.text(sanitizePrintText(String(payroll.employeeName || "Employee")), 14, y)
  y += 5
  pdf.setFont("helvetica", "normal")
  pdf.setFontSize(9)
  pdf.setTextColor(80, 80, 80)
  const meta = [
    String(payroll.employeeNumber || ""),
    payroll.departmentName ? String(payroll.departmentName) : "",
    payroll.paymentStatus ? `Status: ${String(payroll.paymentStatus)}` : "",
  ]
    .filter(Boolean)
    .join(" · ")
  pdf.text(sanitizePrintText(meta), 14, y)
  pdf.setTextColor(0, 0, 0)
  y += 10

  y = line(pdf, "Base salary", kes(parseAmount(payroll.baseSalary)), y)
  y = line(pdf, "Allowances", kes(parseAmount(payroll.allowances)), y)
  y = line(pdf, "Overtime", kes(parseAmount(payroll.overtime)), y)
  y = line(pdf, "Bonuses", kes(parseAmount(payroll.bonuses)), y)
  y = line(pdf, "Gross pay", kes(parseAmount(payroll.grossSalary)), y, true)
  y += 4

  y = line(pdf, "PAYE", kes(parseAmount(payroll.tax)), y)
  y = line(pdf, "NSSF", kes(parseAmount(payroll.nssf)), y)
  y = line(pdf, "SHA (SHIF)", kes(parseAmount(payroll.nhif)), y)
  y = line(pdf, "Housing levy & other", kes(parseAmount(payroll.otherDeductions)), y)
  y = line(pdf, "Other deductions", kes(parseAmount(payroll.deductions)), y)

  const totalDed =
    parseAmount(payroll.tax) +
    parseAmount(payroll.nssf) +
    parseAmount(payroll.nhif) +
    parseAmount(payroll.otherDeductions) +
    parseAmount(payroll.deductions)
  y = line(pdf, "Total deductions", kes(totalDed), y, true)
  y += 6
  y = line(pdf, "Net pay", kes(parseAmount(payroll.netSalary)), y, true)

  if (payroll.bankName || payroll.bankAccount) {
    y += 8
    pdf.setFontSize(9)
    pdf.setTextColor(80, 80, 80)
    pdf.text(
      sanitizePrintText(
        `Bank: ${payroll.bankName || "—"} · ${payroll.bankAccount || "—"}${payroll.bankBranch ? ` (${payroll.bankBranch})` : ""}`
      ),
      14,
      y
    )
    pdf.setTextColor(0, 0, 0)
  }

  pdf.setFontSize(7)
  pdf.setTextColor(120, 120, 120)
  pdf.text(sanitizePrintText(`Generated by ${branding.productName} · Confidential`), 14, 285)

  return pdf
}

export async function downloadPayslipPdf(payroll: PayslipRow) {
  if (typeof window === "undefined") return
  const pdf = await buildPayslipPdf(payroll)
  const num = String(payroll.payrollNumber || payroll.payrollId || "payslip").replace(/\s+/g, "-")
  pdf.save(`payslip-${num}.pdf`)
}

export async function payslipPdfToBase64(payroll: PayslipRow): Promise<string> {
  const pdf = await buildPayslipPdf(payroll)
  const dataUri = pdf.output("datauristring")
  const base64 = dataUri.split(",")[1] || ""
  return base64
}
